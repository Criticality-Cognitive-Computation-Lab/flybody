"""Walking task driven by a CPG controller."""
# ruff: noqa: F821

from pathlib import Path

import numpy as np
import torch
import torch.nn as nn

from dm_control import mjcf
from dm_control.utils import rewards

from flybody.tasks.base import Walking
from flybody.tasks.constants import (_TERMINAL_ANGVEL, _TERMINAL_LINVEL)
from flybody.tasks.cpg import CPGController


class CPGActionMapper(nn.Module):
    """Notebook-consistent MLP mapping from CPG 48D output to leg 48D action."""

    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(48, 512),
            nn.ReLU(),
            nn.Linear(512, 256),
            nn.ReLU(),
            nn.Linear(256, 48),
        )

    def forward(self, x):
        return self.net(x)


class WalkCPG(Walking):
    """Class for open-loop CPG walking control."""

    def __init__(
        self,
        cpg_controller: CPGController,
        mapping_model_path: str | None,
        claw_friction: float | None = 1.0,
        **kwargs,
    ):
        """Walking task where leg joints are generated by a CPG controller.

        Args:
            cpg_controller: Configured CPG controller returning 48 leg-joint
                actions in the environment leg order.
            mapping_model_path: Path to notebook MLP mapping checkpoint
                (`cpg_mapping_model.pth`) used to map CPG output to final
                leg commands.
            claw_friction: Friction of claw.
            **kwargs: Arguments passed to the superclass constructor.
        """
        super().__init__(add_ghost=False, **kwargs)

        self._cpg_controller = cpg_controller
        self._initial_cpg_phases = self._cpg_controller.cpg_network.curr_phases.copy()
        self._initial_cpg_magnitudes = self._cpg_controller.cpg_network.curr_magnitudes.copy()

        self._legs_action_indices = np.asarray(
            self._walker._action_indices["legs"], dtype=int
        )
        if self._legs_action_indices.size != len(self._cpg_controller.all_leg_dofs):
            raise ValueError(
                "Leg action dimension mismatch between walker action space and CPG output."
            )

        if mapping_model_path is None:
            raise ValueError("mapping_model_path must be provided for notebook-consistent WalkCPG.")

        model_path = Path(mapping_model_path).expanduser().resolve()
        if not model_path.exists():
            raise FileNotFoundError(f"Missing CPG mapping model checkpoint: {model_path}")

        self._mapping_model = CPGActionMapper()
        state_dict = torch.load(str(model_path), map_location="cpu", weights_only=True)
        self._mapping_model.load_state_dict(state_dict)
        self._mapping_model.eval()

        # Notebook-style left/right gain modulation for phase-based turning.
        self._leg_order = ["LF", "RF", "LM", "RM", "LH", "RH"]
        self._left_leg_gain = 1.0
        self._right_leg_gain = 1.0

        # Maybe change default claw friction.
        if claw_friction is not None:
            self._walker.mjcf_model.find(
                "default", "adhesion-collision"
            ).geom.friction = (claw_friction,)

    def initialize_episode(self, physics: "mjcf.Physics", random_state: np.random.RandomState):
        """Set initial pose and reset CPG state at episode start."""
        super().initialize_episode(physics, random_state)

        self._cpg_controller.cpg_network.reset(
            init_phases=self._initial_cpg_phases,
            init_magnitudes=self._initial_cpg_magnitudes,
        )

        # Keep wings in retracted pose in walking setup.
        physics.bind(self._wing_joints).qpos = self._wing_springrefs

    def before_step(self, physics: "mjcf.Physics", action, random_state: np.random.RandomState):
        """Ignore incoming leg actions and drive legs with CPG output."""
        base_action = self._cpg_controller.step()["joints"]
        with torch.no_grad():
            base_action = (
                self._mapping_model(torch.from_numpy(base_action).float())
                .detach()
                .cpu()
                .numpy()
            )

        joints_48 = base_action.reshape(6, 8)
        leg_gains = {
            "LF": self._left_leg_gain,
            "RF": self._right_leg_gain,
            "LM": self._left_leg_gain,
            "RM": self._right_leg_gain,
            "LH": self._left_leg_gain,
            "RH": self._right_leg_gain,
        }
        gain_vec = np.array([leg_gains[leg] for leg in self._leg_order], dtype=np.float32)
        base_action = (joints_48 * gain_vec[:, None]).reshape(-1)

        cpg_action = np.asarray(action).copy()
        cpg_action[self._legs_action_indices] = base_action

        # Protect from rare NaN actions.
        cpg_action[np.isnan(cpg_action)] = 0.0

        super().before_step(physics, cpg_action, random_state)

    def set_leg_gains(self, left_gain: float, right_gain: float) -> None:
        """Set notebook-style per-side leg gains for phase-based control."""
        self._left_leg_gain = float(left_gain)
        self._right_leg_gain = float(right_gain)

    def get_reward_factors(self, physics):
        """Returns factorized reward terms."""
        # Reward for wing retraction.
        qpos_diff = physics.bind(self._wing_joints).qpos - self._wing_springrefs
        retract_wings = rewards.tolerance(
            qpos_diff,
            bounds=(0, 0),
            sigmoid="linear",
            margin=3.0,
            value_at_margin=0.0,
        )

        return np.hstack((np.array([1.0]), retract_wings))

    def check_termination(self, physics: "mjcf.Physics") -> bool:
        """Check various termination conditions."""
        linvel = np.linalg.norm(self._walker.observables.velocimeter(physics))
        angvel = np.linalg.norm(self._walker.observables.gyro(physics))

        return (
            linvel > _TERMINAL_LINVEL
            or angvel > _TERMINAL_ANGVEL
            or super().check_termination(physics)
        )

